package basic;

public class ConditionalStatement {

	public static void main(String[] args) {
		int numbers = 0;
		if(numbers == 0) {
			System.out.println("The number is zero");
			}else if(numbers < 0) {
				System.out.println("The number is negative");
			}else
				System.out.println("The number is positive");
	}

}
